// Compiles Noir circuits with nargo and embeds the artifacts into @arkivzk/zk as TS modules.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const root = path.resolve(import.meta.dirname, "..");
const nargo = fs.existsSync(path.join(os.homedir(), ".nargo/bin/nargo")) ? path.join(os.homedir(), ".nargo/bin/nargo") : "nargo";
const out = path.join(root, "packages/zk/src/circuits");
fs.mkdirSync(out, { recursive: true });
for (const name of ["commit", "range"]) {
  const dir = path.join(root, "circuits", name);
  execSync(`${nargo} compile`, { cwd: dir, stdio: "inherit" });
  const json = fs.readFileSync(path.join(dir, "target", `arkivzk_${name}.json`), "utf8");
  fs.writeFileSync(path.join(out, `${name}.ts`), `// generated by scripts/build-circuits.mjs - do not edit\nconst circuit = ${json.trim()} as const;\nexport default circuit;\n`);
  console.log(`embedded ${name}`);
}
